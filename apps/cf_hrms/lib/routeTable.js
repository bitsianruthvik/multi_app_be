/**
 * routeTable.js — every route of this app and the right it asks for, read from
 * the routers themselves. (TM/CF_HRMS_HIRING_SPEC.md §12.1.)
 *
 * `guard(...)` (lib/http.js) leaves what it asks for on its middleware
 * (`hrmsGuard`). This file walks a router, finds that on each route, and writes
 * the table: ACCESS.md is its output (scripts/make-access-doc.mjs) and the test
 * that no route is unguarded reads the same rows — so the document cannot say
 * one thing while the code does another.
 *
 * Pure: it takes a router and returns rows and text.
 */
import { AREAS, NAMED, areaTag, isKnownTag } from './access.js';

/** Routes that are open on purpose, with the reason. Anything else without a guard is a mistake. */
export const PUBLIC_ROUTES = { 'GET /health': 'liveness check; says only that the app is up' };

function collect(router, rows) {
  for (const layer of router.stack ?? []) {
    if (layer.route) {
      const handlers = layer.route.stack.map((l) => l.handle);
      const guard = handlers.map((h) => h.hrmsGuard).find(Boolean) ?? null;
      const steps = handlers.map((h) => h.hrmsStep).filter(Boolean);
      for (const method of Object.keys(layer.route.methods)) {
        rows.push({ method: method.toUpperCase(), path: layer.route.path, guard, steps });
      }
    } else if (layer.handle?.stack) {
      collect(layer.handle, rows);
    }
  }
  return rows;
}

/** [{ method, path, guard: { signedIn, anyOf, also, note } | null, steps }] in the order the routers declare them. */
export function routeTable(router) {
  return collect(router, []);
}

/** What is wrong with a table: a route with no guard, or a guard naming a right that does not exist. */
export function routeTableProblems(rows) {
  const problems = [];
  const seen = new Map();
  for (const r of rows) {
    const key = `${r.method} ${r.path}`;
    if (seen.has(key)) problems.push(`${key} is declared twice.`);
    seen.set(key, true);
    if (!r.guard) {
      if (!(key in PUBLIC_ROUTES)) problems.push(`${key} has no guard.`);
      continue;
    }
    if (key in PUBLIC_ROUTES) problems.push(`${key} is listed as public but has a guard.`);
    for (const tag of [...r.guard.anyOf, ...r.guard.also]) if (!isKnownTag(tag)) problems.push(`${key} asks for "${tag}", which is not a right of this app.`);
    if (!r.guard.signedIn && !r.guard.anyOf.length) problems.push(`${key} has a guard that asks for nothing.`);
  }
  return problems;
}

const short = (tag) => `\`${tag}\``;
function rightOf(r) {
  const key = `${r.method} ${r.path}`;
  if (!r.guard) return key in PUBLIC_ROUTES ? `open — ${PUBLIC_ROUTES[key]}` : '**NO GUARD**';
  const g = r.guard;
  let text = g.signedIn ? 'any login with access to the app' : g.anyOf.map(short).join(' or ');
  if (g.also.length) text += ` **and** ${g.also.map(short).join(' and ')}`;
  return text;
}
function alsoOf(r) {
  const notes = [];
  for (const s of r.steps) notes.push(s);
  if (r.guard?.note) notes.push(r.guard.note);
  return notes.join('; ');
}

const AREA_OF_FILE = [
  ['Access', (p) => p.startsWith('/access')],
  ['Your own place (the employee self view)', (p) => p.startsWith('/user/me')],
  ['Organisation, time and setup lists', (p) => p.startsWith('/organisation')],
  ['Roles and libraries', (p) => p.startsWith('/role')],
  ['Positions and the org chart', (p) => p.startsWith('/position') || p.startsWith('/orgchart')],
  ['Hiring', (p) => p.startsWith('/hiring')],
  ['Employees', (p) => p.startsWith('/people')],
  ['Work of a person (assignments)', (p) => p.startsWith('/assignment') || p.startsWith('/work-assignment')],
  ['Documents', (p) => p.startsWith('/documents')],
  ['Leave', (p) => p.startsWith('/leave')],
  ['Code formats', (p) => p.startsWith('/codegen')],
  ['Excel', (p) => p.startsWith('/excel')],
  ['Everything else', () => true],
];
// A hiring is started on a position and lives under /hirings; both belong with Hiring.
const sectionOf = (path) => (/^\/hirings|^\/positions\/:id\/hiring$/.test(path) ? 'Hiring' : AREA_OF_FILE.find(([, test]) => test(path))[0]);

/** ACCESS.md, whole. */
export function renderAccessDoc(rows) {
  const out = [];
  out.push('# CF_HRMS — what each route asks for');
  out.push('');
  out.push('GENERATED by `apps/cf_hrms/scripts/make-access-doc.mjs` from the routers themselves (`lib/routeTable.js`). Do not edit by hand: change the `guard(...)` on the route and run the script. `scripts/cf_hrms/access_test.mjs` fails when this file is out of date, when a route has no guard, or when a guard names a right that does not exist.');
  out.push('');
  out.push('## The rights');
  out.push('');
  out.push('One tag = one thing a person may do. The Owner (the company’s `admin` role) holds all of them.');
  out.push('');
  out.push('| Area | Screens | view | edit | remove | upload |');
  out.push('|---|---|---|---|---|---|');
  for (const a of AREAS) {
    const cell = (r) => (a.rights.includes(r) ? short(areaTag(a.key, r)) : '–');
    out.push(`| ${a.label} | ${a.screens.join(', ')} | ${cell('view')} | ${cell('edit')} | ${cell('remove')} | ${cell('upload')} |`);
  }
  out.push('');
  out.push('| Named right | What it is |');
  out.push('|---|---|');
  for (const n of NAMED) out.push(`| ${short(n.tag)} | ${n.label}. ${n.hint} |`);
  out.push('');
  out.push('How to read the tables below:');
  out.push('- **a or b** — holding either is enough (a picker two screens share).');
  out.push('- **and** — both are needed.');
  out.push('- **scope: the position / the person / the department** — for a login whose access role is “only their department and below”, the thing named must be inside it (403 `OUT_OF_SCOPE`). A whole-company login is not affected.');
  out.push('- **whole-company logins only** — the thing belongs to no department, so a department-scoped login cannot change it.');
  out.push('- `cf_hrms_contact_view` and `cf_hrms_pay_view` also change what a route RETURNS: without them contact details and pay are removed from the answer on the server.');
  out.push('- **filters: …** — the search and filters that list takes in its address (`?q=&status=`); it answers `total` and `count` beside its rows.');
  out.push('- `upload` rights guard the Excel uploads (the Excel section).');
  out.push('');

  const sections = new Map();
  for (const r of rows) {
    const name = sectionOf(r.path);
    sections.set(name, [...(sections.get(name) ?? []), r]);
  }
  for (const [name] of AREA_OF_FILE) {
    const list = sections.get(name);
    if (!list?.length) continue;
    out.push(`## ${name}`);
    out.push('');
    out.push('| Route | Right | Also |');
    out.push('|---|---|---|');
    for (const r of list) out.push(`| \`${r.method} ${r.path}\` | ${rightOf(r)} | ${alsoOf(r)} |`);
    out.push('');
  }
  out.push(`${rows.length} routes.`);
  out.push('');
  return out.join('\n');
}

export default { PUBLIC_ROUTES, routeTable, routeTableProblems, renderAccessDoc };
